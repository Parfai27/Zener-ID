export type Lang = 'En' | 'Fr' | 'Rw' | 'Sw'
export const LANGS: Array<[Lang, string, string]> = [['En', 'English', 'en'], ['Fr', 'Français', 'fr'], ['Rw', 'Kinyarwanda', 'rw'], ['Sw', 'Kiswahili', 'sw']]
const DICTS: Record<Lang, Dict> = { En: en, Fr: fr, Rw: rw, Sw: sw }

export type T = (key: keyof Dict, vars?: Record<string, string>) => string
export function makeT(lang: Lang): T {
  const d = DICTS[lang]
  return (key, vars) => (d[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k) => vars?.[k] ?? '')
}

export const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>({ lang: 'En', setLang: () => {}, t: makeT('En') })
export const useT = () => useContext(LangCtx).t
export const useLang = () => useContext(LangCtx)

export function initialLang(): Lang {
  try {
    const saved = sessionStorage.getItem('zid.lang') as Lang | null
    if (saved && saved in DICTS) return saved
  } catch { /* ignore */ }
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase()
  return (LANGS.find(l => l[2] === nav)?.[0]) || 'En'
}
